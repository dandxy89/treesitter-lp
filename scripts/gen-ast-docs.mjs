#!/usr/bin/env node
// Renders src/node-types.json as docs/ast-nodes.md.
//
// Usage: node scripts/gen-ast-docs.mjs
//
// Output is deterministic (sorted, no timestamps), so CI can regenerate the
// file and fail on `git diff --exit-code docs/ast-nodes.md`.
//
// The frozen surface below lists the named node kinds and fields that
// downstream consumers (lp-lsp) rely on. Renaming or removing one is a
// breaking change to the parse tree, so the script fails if any is missing.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const nodeTypesPath = join(root, "src", "node-types.json");
const outPath = join(root, "docs", "ast-nodes.md");

const FROZEN_KINDS = [
  "source_file",
  "sense",
  "multi_objectives_keyword",
  "objectives_section",
  "named_objective",
  "objective_name",
  "objective_attribute",
  "attribute_name",
  "constraints_section",
  "subject_to_keyword",
  "lazy_constraints_section",
  "lazy_constraints_keyword",
  "user_cuts_section",
  "user_cuts_keyword",
  "general_constraints_section",
  "general_constraints_keyword",
  "general_constraint",
  "function_name",
  "constraint",
  "constraint_name",
  "indicator",
  "linear_expression",
  "term",
  "quadratic_block",
  "quadratic_term",
  "comparison_operator",
  "bounds_section",
  "bounds_keyword",
  "bound_declaration",
  "free_keyword",
  "generals_section",
  "generals_keyword",
  "integers_section",
  "integers_keyword",
  "binaries_section",
  "binaries_keyword",
  "semi_continuous_section",
  "semi_continuous_keyword",
  "sos_section",
  "sos_keyword",
  "sos_constraint_header",
  "sos_name",
  "sos_type",
  "sos_entry",
  "end_marker",
  "identifier",
  "number",
  "infinity",
  "line_comment",
  "block_comment",
];
const FROZEN_FIELDS = ["function", "name"];

const frozen = new Set(FROZEN_KINDS);

/** Formats a child type as `kind` (named) or `"token"` (anonymous). */
const label = (t) => (t.named ? `\`${t.type}\`` : `\`"${t.type}"\``);

/** Lists a `types` array, or `—` when there are none. */
const list = (types) =>
  types.length === 0 ? "—" : types.map(label).join(", ");

const describe = (multiplicity) => {
  const { multiple, required } = multiplicity;
  if (required && multiple) return "one or more";
  if (required) return "exactly one";
  if (multiple) return "zero or more";
  return "zero or one";
};

const raw = JSON.parse(readFileSync(nodeTypesPath, "utf8"));
const named = raw.filter((n) => n.named && !n.type.startsWith("_"));
named.sort((a, b) => a.type.localeCompare(b.type));

const kinds = new Set(named.map((n) => n.type));
const missingKinds = FROZEN_KINDS.filter((k) => !kinds.has(k));
if (missingKinds.length > 0) {
  throw new Error(
    `frozen node kinds missing from node-types.json: ${missingKinds.join(", ")}`,
  );
}
const fieldNames = new Set(named.flatMap((n) => Object.keys(n.fields ?? {})));
const missingFields = FROZEN_FIELDS.filter((f) => !fieldNames.has(f));
if (missingFields.length > 0) {
  throw new Error(
    `frozen fields missing from node-types.json: ${missingFields.join(", ")}`,
  );
}

const lines = [];
lines.push(
  "<!-- Generated by scripts/gen-ast-docs.mjs from src/node-types.json. Do not edit by hand. -->",
);
lines.push("");
lines.push("# AST node types");
lines.push("");
lines.push(
  `The grammar has ${named.length} named node types. Anonymous tokens (keywords and punctuation written as \`"+"\`, \`"<="\`, ...) appear only as children. Hidden rules (names starting with \`_\`) are not part of the tree and are not listed.`,
);
lines.push("");
lines.push(
  `Frozen kinds (${FROZEN_KINDS.length}) and the fields \`function\` and \`name\` are marked **frozen**: they are relied on by downstream consumers, so renaming or removing one is a breaking change to the parse tree.`,
);
lines.push("");
lines.push("| Node | Frozen |");
lines.push("| --- | --- |");
for (const node of named) {
  lines.push(
    `| [\`${node.type}\`](#${node.type}) | ${frozen.has(node.type) ? "yes" : ""} |`,
  );
}
lines.push("");

for (const node of named) {
  lines.push(`## \`${node.type}\``);
  lines.push("");
  lines.push(frozen.has(node.type) ? "Frozen: yes." : "Frozen: no.");
  lines.push("");

  const fields = Object.entries(node.fields ?? {}).sort(([a], [b]) =>
    a.localeCompare(b),
  );
  if (fields.length > 0) {
    lines.push("Fields:");
    lines.push("");
    lines.push("| Field | Cardinality | Types |");
    lines.push("| --- | --- | --- |");
    for (const [name, spec] of fields) {
      const field = FROZEN_FIELDS.includes(name)
        ? `\`${name}\` (frozen)`
        : `\`${name}\``;
      lines.push(`| ${field} | ${describe(spec)} | ${list(spec.types)} |`);
    }
    lines.push("");
  }

  if (node.children && node.children.types.length > 0) {
    const { multiple, required } = node.children;
    lines.push("Children:");
    lines.push("");
    lines.push(
      `- Repeated: ${multiple ? "yes" : "no"}. At least one required: ${required ? "yes" : "no"}.`,
    );
    lines.push(`- Types: ${list(node.children.types)}`);
    lines.push("");
  }

  if (!node.children && fields.length === 0) {
    lines.push("No fields or children in `node-types.json`: a leaf node.");
    lines.push("");
  }
}

writeFileSync(outPath, `${lines.join("\n").replace(/\n+$/, "")}\n`);
console.log(`wrote ${outPath} (${named.length} named node types)`);
